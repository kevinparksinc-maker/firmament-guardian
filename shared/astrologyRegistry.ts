export function getTechniqueById(id: string): AstrologyTechniqueEntry | undefined {
  return ASTROLOGY_TECHNIQUE_REGISTRY.find((item) => item.id === id);
}

export function getTechniquesByTradition(tradition: AstrologyTradition): AstrologyTechniqueEntry[] {
  return ASTROLOGY_TECHNIQUE_REGISTRY.filter((item) => item.tradition === tradition);
}

export function getTechniquesByStatus(status: VerificationStatus): AstrologyTechniqueEntry[] {
  return ASTROLOGY_TECHNIQUE_REGISTRY.filter((item) => item.verificationStatus === status);
}

export function getTechniqueAuditSummary() {
  const total = ASTROLOGY_TECHNIQUE_REGISTRY.length;
  const verified = ASTROLOGY_TECHNIQUE_REGISTRY.filter((t) => t.verificationStatus === "VERIFIED").length;
  const partial = ASTROLOGY_TECHNIQUE_REGISTRY.filter((t) => t.verificationStatus === "PARTIALLY_IMPLEMENTED").length;
  const knowledgeOnly = ASTROLOGY_TECHNIQUE_REGISTRY.filter((t) => t.verificationStatus === "KNOWLEDGE_ONLY").length;
  const notImplemented = ASTROLOGY_TECHNIQUE_REGISTRY.filter((t) => t.verificationStatus === "NOT_IMPLEMENTED").length;
  return { total, verified, partial, knowledgeOnly, notImplemented };
}
